/**
 * Points section — three glass cards pinned over a 250vh scroll, with a
 * scrubbed background zoom and staggered card entrances (GSAP ScrollTrigger),
 * plus pure-CSS hover texture crossfades on the logo pieces (ported).
 *
 * Scroll behavior (matches the target's observed keyframes):
 * - bg zoom: scale 1.2 at 0 → 1.0751 at ~0.45 → 1 at 1
 * - cards: each enters over its own progress window [i*0.16, i*0.16+0.35],
 *   translating 1750px → 0 (ease none, scrub)
 */
export function Points() {
  const pointsRef = useRef<HTMLDivElement>(null);
  const bgRef = useRef<HTMLDivElement>(null);
  const itemRefs = useRef<(HTMLDivElement | null)[]>([]);

  useEffect(() => {
    const points = pointsRef.current;
    const bg = bgRef.current;
    if (!points || !bg) return;

    // Desktop only — below 992px the ported CSS makes the section static.
    const mm = gsap.matchMedia();
    mm.add("(min-width: 992px)", () => {
      const items = itemRefs.current.filter(
        (el): el is HTMLDivElement => el !== null,
      );
      if (items.length === 0) return;
      const tl = gsap.timeline({
        defaults: { ease: "none" },
        scrollTrigger: {
          trigger: points,
          start: "top top",
          end: "bottom bottom",
          scrub: true,
        },
      });
      tl.fromTo(
        bg,
        { scale: 1.2 },
        { scale: 1.0751, duration: 0.45, immediateRender: true },
        0,
      ).to(bg, { scale: 1, duration: 0.55 }, 0.45);
      items.forEach((item, i) => {
        tl.fromTo(
          item,
          { y: 1750 },
          { y: 0, duration: 0.35, immediateRender: true },
          i * 0.16,
        );
      });
    });
    return () => mm.revert();
  }, []);

  return (
    <section change-nav-color="white" className="section">
      <div className="container">
        <div ref={pointsRef} className="points">
          <div className="points_sticky">
            <div ref={bgRef} className="points_bg-parent">
              <img
                src="/sites/ciridae-0e008832/root-8a5edab2/images/Hero.webp"
                loading="lazy"
                alt=""
                className="img-cover"
              />
            </div>
            <div className="points_content">
              {POINTS_ITEMS.map((item, i) => (
                <div
                  key={item.index}
                  ref={(el) => {
                    itemRefs.current[i] = el;
                  }}
                  className="points_item"
                >
                  <div className="v-flex-center-top gap-40">
                    <div className="tag">
                      <div className="f-11 font-mono lh-110 caps">
                        {item.index}
                      </div>
                    </div>
                    <div
                      style={{ "--max-w": "50ch" } as CSSProperties}
                      data-module=""
                      className="custom-descr caps f-20 lh-100 -ls-02"
                    >
                      <div className="rich-inherit w-richtext">
                        <h3>{item.title}</h3>
                      </div>
                    </div>
                  </div>
                  <div className="points_logo">
                    <div className="logo-pieces">
                      {LOGO_PIECES.map((piece, p) => (
                        <svg
                          key={p}
                          viewBox={piece.viewBox}
                          data-morph={piece.morph}
                          className={piece.className}
                        >
                          <path fill="currentColor" d={piece.d} />
                        </svg>
                      ))}
                    </div>
                  </div>
                  <div className="points_bottom f-15 lh-120 -ls-01 font-body">
                    <p>{item.description}</p>
                  </div>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
